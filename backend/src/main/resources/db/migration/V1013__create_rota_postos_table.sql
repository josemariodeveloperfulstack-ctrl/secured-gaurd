CREATE TABLE rota_postos (
    id_rota UUID NOT NULL,
    id_posto UUID NOT NULL,
    ordem_visita INTEGER NOT NULL,
    PRIMARY KEY (id_rota, id_posto),
    FOREIGN KEY (id_rota) REFERENCES rotas(id) ON DELETE CASCADE,
    FOREIGN KEY (id_posto) REFERENCES postos(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
