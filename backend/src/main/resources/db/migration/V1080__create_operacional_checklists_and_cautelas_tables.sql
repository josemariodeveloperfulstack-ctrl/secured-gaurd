-- V1080: Criação das tabelas do Módulo Operacional
-- 1. Checklist de Radiocomunicação (HT)
CREATE TABLE IF NOT EXISTS radio_checklists (
    id BIGSERIAL PRIMARY KEY,
    document_code VARCHAR(50) DEFAULT 'CK-ALMOX-HT',
    document_version VARCHAR(20) DEFAULT '02',
    document_date DATE,
    movement_type VARCHAR(30) NOT NULL DEFAULT 'RETIRADA',
    checklist_date DATE NOT NULL,
    checklist_time TIME,
    vigilante_name VARCHAR(150),
    vigilante_registration VARCHAR(50),
    work_post_name VARCHAR(150),
    radio_asset_id VARCHAR(50),
    radio_serial_number VARCHAR(100),
    carcaca_externa BOOLEAN DEFAULT false,
    antena BOOLEAN DEFAULT false,
    clip_cinto BOOLEAN DEFAULT false,
    conector_acessorios BOOLEAN DEFAULT false,
    encaixe_bateria BOOLEAN DEFAULT false,
    nivel_carga BOOLEAN DEFAULT false,
    contatos_carga BOOLEAN DEFAULT false,
    botao_volume BOOLEAN DEFAULT false,
    seletor_canais BOOLEAN DEFAULT false,
    botao_ptt BOOLEAN DEFAULT false,
    teste_comunicacao_pratica BOOLEAN DEFAULT false,
    fone_ouvido_lapela BOOLEAN DEFAULT false,
    carregador_mesa_fonte BOOLEAN DEFAULT false,
    conformity_status VARCHAR(30) DEFAULT 'CONFORME',
    observations TEXT,
    vigilante_signature_base64 TEXT,
    almoxarife_name VARCHAR(150),
    almoxarife_signature_base64 TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 2. Checklist Diário de Viatura Operacional
CREATE TABLE IF NOT EXISTS vehicle_checklists (
    id BIGSERIAL PRIMARY KEY,
    plate VARCHAR(20) NOT NULL,
    model VARCHAR(100),
    current_km INTEGER,
    checklist_date DATE NOT NULL,
    checklist_time TIME,
    shift VARCHAR(20) NOT NULL DEFAULT 'DIA',
    supervisor_name VARCHAR(150),
    employee_name VARCHAR(150),
    employee_registration VARCHAR(50),
    dianteira BOOLEAN DEFAULT false,
    laterais BOOLEAN DEFAULT false,
    vidros_retrovisores BOOLEAN DEFAULT false,
    identificacao_visual BOOLEAN DEFAULT false,
    farois_lanternas BOOLEAN DEFAULT false,
    giroflex_sirene BOOLEAN DEFAULT false,
    buzina BOOLEAN DEFAULT false,
    pneus BOOLEAN DEFAULT false,
    niveis BOOLEAN DEFAULT false,
    painel BOOLEAN DEFAULT false,
    documentacao BOOLEAN DEFAULT false,
    ferramentas_emergencia BOOLEAN DEFAULT false,
    extintor_incendio BOOLEAN DEFAULT false,
    kit_prancheta BOOLEAN DEFAULT false,
    conformity_status VARCHAR(30) DEFAULT 'CONFORME',
    observations TEXT,
    signature_base64 TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 3. Termo de Acautelamento e Responsabilidade de Arma de Fogo e Munição
CREATE TABLE IF NOT EXISTS firearm_acautelamentos (
    id BIGSERIAL PRIMARY KEY,
    company_name VARCHAR(150) DEFAULT 'SECURED GUARD SEGURANÇA PRIVADA',
    vigilante_name VARCHAR(150) NOT NULL,
    registration VARCHAR(50),
    cnv_number VARCHAR(50),
    cpf VARCHAR(20),
    work_post_name VARCHAR(150),
    recycling_expiration_date DATE,
    weapon_type VARCHAR(50),
    brand VARCHAR(80),
    caliber VARCHAR(30),
    shot_capacity INTEGER,
    serial_number VARCHAR(80) NOT NULL,
    craf_number VARCHAR(80),
    ammo_quantity INTEGER,
    ammo_type VARCHAR(50),
    ammo_lot VARCHAR(80),
    accessories VARCHAR(250),
    mecanismo_disparo_ok BOOLEAN DEFAULT true,
    cano_desobstruido_ok BOOLEAN DEFAULT true,
    conservation_state VARCHAR(30) DEFAULT 'Excelente',
    status VARCHAR(30) DEFAULT 'ATIVO',
    city_uf VARCHAR(100) DEFAULT 'São Paulo - SP',
    term_date DATE,
    observations TEXT,
    vigilante_signature_base64 TEXT,
    armeiro_name VARCHAR(150),
    armeiro_signature_base64 TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 4. Termo de Cautela e Responsabilidade de Equipamentos
CREATE TABLE IF NOT EXISTS equipment_cautelas (
